import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { END, START } from "./render.js";
import { sha256 } from "./util.js";

/** Hash of what the block depends on, so `check` can tell when it is stale without the network. */
export function depsHash(modelId: string, cutoff: string, marginDays: number, deps: { name: string; pinned?: string }[]): string {
  const key = JSON.stringify({
    v: 1,
    modelId,
    cutoff,
    marginDays,
    deps: deps.map((d) => [d.name, d.pinned ?? "?"]).sort((a, b) => a[0]!.localeCompare(b[0]!)),
  });
  return sha256(key).slice(0, 12);
}

/**
 * AGENTS.md unless the project only has a CLAUDE.md. (Claude Code reads CLAUDE.md;
 * Codex, Cursor, Gemini CLI and others read AGENTS.md.)
 */
export function defaultTarget(root: string): string {
  const agents = join(root, "AGENTS.md");
  const claude = join(root, "CLAUDE.md");
  if (!existsSync(agents) && existsSync(claude)) return claude;
  return agents;
}

async function readIfExists(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch {
    return undefined;
  }
}

const blockRe = () => new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}\\n?`);
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export async function readBlock(path: string): Promise<{ block?: string; hash?: string; text?: string }> {
  const text = await readIfExists(path);
  const m = text?.match(blockRe());
  const hash = m?.[0].match(/deps=([0-9a-f]{12})/)?.[1];
  return { block: m?.[0], hash, text };
}

/** Insert or replace the block. Text outside the markers is left byte-for-byte as it was. */
export function applyBlock(existing: string | undefined, block: string): string {
  const withNewline = block.endsWith("\n") ? block : block + "\n";
  if (!existing) return withNewline;
  if (blockRe().test(existing)) return existing.replace(blockRe(), withNewline);
  const sep = existing.endsWith("\n\n") ? "" : existing.endsWith("\n") ? "\n" : "\n\n";
  return existing + sep + withNewline;
}

/** Drop only the date: model=, cutoff= and deps= must match, or `check` would stay red after a re-run. */
const withoutDate = (block: string) => block.replace(/(<!-- generated by stalemap )\d{4}-\d{2}-\d{2}( ·)/, "$1$2").trim();

/** Same block apart from the generated-on date, so re-running doesn't rewrite the file just for the date. */
export function sameBlock(a: string | undefined, b: string): boolean {
  return a !== undefined && withoutDate(a) === withoutDate(b);
}

export function removeBlock(existing: string): string {
  return existing.replace(new RegExp(`\\n?${escape(START)}[\\s\\S]*?${escape(END)}\\n?`), "\n").replace(/\n{2,}$/, "\n");
}
