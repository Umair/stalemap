import assert from "node:assert/strict";
import { test } from "node:test";
import type { PackageReport } from "../src/analyze.ts";
import { applyBlock, depsHash, removeBlock, sameBlock } from "../src/block.ts";
import { END, START, renderBlock } from "../src/render.ts";
import { estimateTokens } from "../src/util.ts";

const block = `${START}\n<!-- generated by stalemap 2026-10-16 · deps=abc -->\nnotes\n${END}`;

test("applyBlock appends, replaces in place and leaves other text untouched", () => {
  assert.equal(applyBlock(undefined, block), block + "\n");
  const appended = applyBlock("# Notes\n\nUse pnpm.\n", block);
  assert.equal(appended, `# Notes\n\nUse pnpm.\n\n${block}\n`);
  const replaced = applyBlock(appended + "\nAfter.\n", block.replace("notes", "new notes"));
  assert.match(replaced, /new notes/);
  assert.match(replaced, /^# Notes\n\nUse pnpm\.\n\n/);
  assert.match(replaced, /\nAfter\.\n$/);
  assert.equal(applyBlock(appended, block), appended, "idempotent");
});

test("removeBlock restores the original file", () => {
  assert.equal(removeBlock(applyBlock("# Notes\n\nUse pnpm.\n", block)), "# Notes\n\nUse pnpm.\n");
});

test("depsHash ignores dependency order but not versions", () => {
  const a = depsHash("m", "2026-06-30", 30, [{ name: "a", pinned: "1.0.0" }, { name: "b", pinned: "2.0.0" }]);
  const b = depsHash("m", "2026-06-30", 30, [{ name: "b", pinned: "2.0.0" }, { name: "a", pinned: "1.0.0" }]);
  const c = depsHash("m", "2026-06-30", 30, [{ name: "a", pinned: "1.0.1" }, { name: "b", pinned: "2.0.0" }]);
  assert.equal(a, b);
  assert.notEqual(a, c);
});

test("renderBlock stays within the token budget and keeps each package's top note", () => {
  const reports: PackageReport[] = Array.from({ length: 8 }, (_, i) => ({
    name: `pkg${i}`,
    status: "changed",
    pinned: "2.0.0",
    baseline: { version: "1.0.0", publishedAt: "" },
    major: true,
    used: true,
    usedNames: [],
    files: [],
    types: {
      analyzed: ["."],
      noTypes: false,
      changes: Array.from({ length: 6 }, (_, j) => ({
        subpath: ".",
        symbol: `api${j}`,
        kind: "removed" as const,
        detail: `\`api${j}\` was removed and this sentence is padding to make the note long enough to matter`,
        used: true,
        severity: 9,
      })),
    },
  }));
  const model = { id: "m", cutoff: new Date("2026-06-30"), cutoffSource: "test", modelSource: "--model" };
  const out = renderBlock(reports, { model, hash: "abc", budgetTokens: 600, maxBulletsPerPackage: 5, generatedAt: new Date() }, 4);
  assert.ok(estimateTokens(out.block) <= 650, `block is ${estimateTokens(out.block)} tokens`);
  assert.ok(out.dropped > 0);
  assert.ok(out.block.startsWith(START) && out.block.endsWith(END));
});

test("sameBlock ignores the generated-on date and nothing else", () => {
  const line = (date: string, deps: string, model = "m") => `${START}\n<!-- generated by stalemap ${date} · model=${model} · cutoff=2025-07-31 · deps=${deps} -->\nnotes\n${END}`;
  assert.ok(sameBlock(line("2026-10-16", "0123456789ab"), line("2026-11-02", "0123456789ab")));
  assert.ok(!sameBlock(line("2026-10-16", "0123456789ab"), line("2026-10-16", "ba9876543210")), "a dependency bump with no new notes still changes deps=");
  assert.ok(!sameBlock(line("2026-10-16", "0123456789ab"), line("2026-10-16", "0123456789ab", "other")));
  assert.ok(!sameBlock(undefined, line("2026-10-16", "0123456789ab")));
});
