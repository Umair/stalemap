test("parseJsonc and formatJson", () => {
  assert.deepEqual(parseJsonc(`{"a": 1}`), { value: { a: 1 }, lossy: false });
  assert.deepEqual(parseJsonc(`{\n  // c\n  "url": "http://x//y", /* b */ "b": [1,],\n}`), { value: { url: "http://x//y", b: [1] }, lossy: true });
  assert.equal(parseJsonc("{ nope"), undefined);
  assert.equal(formatJson({ a: { args: ["-y", "x"], n: [] }, b: [{ c: 1 }] }), `{\n  "a": {\n    "args": ["-y", "x"],\n    "n": []\n  },\n  "b": [\n    {\n      "c": 1\n    }\n  ]\n}`);
});

const hasTomllib = (() => {
  try {
    execFileSync("python3", ["-c", "import tomllib"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
})();
/** Parse with Python's tomllib: throws, with the parser's message, when the TOML is invalid. */
const parseToml = (text: string) => JSON.parse(execFileSync("python3", ["-c", "import sys, json, tomllib; print(json.dumps(tomllib.loads(sys.stdin.read())))"], { input: text, encoding: "utf8" }));

test("Codex config.toml stays valid TOML, or is left alone with what to add by hand", { skip: !hasTomllib && "needs python3 with tomllib" }, async () => {
  const cases: Array<{ toml: string; mcp: string; guard: string; guardFile?: string }> = [
    { toml: `model = "gpt-5.5"\n`, mcp: "update", guard: "create", guardFile: ".codex/hooks.json" },
    { toml: `[mcp_servers]\ndocs.command = "uvx"\n`, mcp: "update", guard: "create" },
    { toml: `mcp_servers.docs.command = "uvx"\n`, mcp: "update", guard: "create" },
    { toml: `[features]\nhooks = true\n`, mcp: "update", guard: "create", guardFile: ".codex/hooks.json" },
    { toml: `[[hooks.PostToolUse]]\nmatcher = "Bash"\n\n[[hooks.PostToolUse.hooks]]\ntype = "command"\ncommand = "./log.sh"\n`, mcp: "update", guard: "update", guardFile: ".codex/config.toml" },
    { toml: `[hooks]\nPreToolUse = [{ matcher = "Bash", hooks = [] }]\n`, mcp: "update", guard: "update", guardFile: ".codex/config.toml" },
    { toml: `hooks.PreToolUse = []\n`, mcp: "update", guard: "update", guardFile: ".codex/config.toml" },
    // stalemap is already there, in forms a [mcp_servers.stalemap] table would clash with
    { toml: `[mcp_servers]\nstalemap.command = "npx"\nstalemap.args = ["-y", "stalemap@latest", "mcp"]\n`, mcp: "unchanged", guard: "create" },
    { toml: `mcp_servers.stalemap.command = "npx"\n`, mcp: "unchanged", guard: "create" },
    { toml: `mcp_servers = { stalemap = { command = "npx" } }\n`, mcp: "unchanged", guard: "create" },
    // layouts a table can't extend
    { toml: `mcp_servers = { docs = { command = "uvx" } }\n`, mcp: "skipped", guard: "create" },
    { toml: `[[mcp_servers]]\nname = "docs"\n`, mcp: "skipped", guard: "create" },
    { toml: `[hooks]\nPostToolUse = [{ matcher = "Bash", hooks = [] }]\n`, mcp: "update", guard: "skipped" },
    { toml: `hooks = { PostToolUse = [] }\n`, mcp: "update", guard: "skipped" },
    { toml: `[hooks.PostToolUse]\nmatcher = "Bash"\n`, mcp: "update", guard: "skipped" },
  ];
  for (const c of cases) {
    const dir = await project({ ".codex/config.toml": c.toml });
    const result = await setupAgent({ agent: "codex", cwd: dir, home: dir });
    const [, mcp, guard] = result.changes;
    const label = JSON.stringify(c.toml);
    assert.deepEqual([mcp!.action, guard!.action], [c.mcp, c.guard], label);
    if (c.guardFile) assert.equal(guard!.file, c.guardFile, label);
    const after = await read(dir, ".codex/config.toml");
    const parsed = parseToml(after); // throws on invalid TOML
    if (mcp!.action === "update") assert.deepEqual(parsed.mcp_servers.stalemap.args, ["-y", "stalemap@latest", "mcp"], label);
    if (guard!.action === "update") assert.ok(parsed.hooks.PostToolUse.some((g: { matcher: string }) => g.matcher === "apply_patch|Edit|Write"), label);
    // What setup says to add by hand fits where it says to add it.
    if (mcp!.action === "skipped" && c.toml.startsWith("mcp_servers = {")) {
      const entry = mcp!.detail!.split("\n").at(-1)!;
      assert.deepEqual(parseToml(c.toml.replace("{ ", `{ ${entry}, `)).mcp_servers.stalemap.args, ["-y", "stalemap@latest", "mcp"], label);
    } else if (mcp!.action === "skipped") assert.match(mcp!.detail!, /add this:\n\[mcp_servers\.stalemap\]/, label);
    if (guard!.action === "skipped") {
      const entry = guard!.detail!.split("\n").at(-1)!;
      assert.match(guard!.detail!, /add this to that PostToolUse array by hand:\n\{ matcher = "apply_patch\|Edit\|Write"/, label);
      if (c.toml.includes("PostToolUse = [")) {
        const fixed = parseToml(c.toml.replace(/PostToolUse = \[/, `PostToolUse = [${entry}, `).replace(/, \]/, "]"));
        assert.equal((fixed.hooks.PostToolUse as Array<{ hooks: Array<{ command: string }> }>)[0]!.hooks[0]!.command, "npx -y stalemap@latest hook post-edit --agent codex", label);
      }
    }
    if (mcp!.action !== "update" && guard!.action !== "update") assert.equal(after, c.toml, `${label} is left as it was`);
    assert.equal((await setupAgent({ agent: "codex", cwd: dir, home: dir })).files.size, 0, `${label}: a re-run changes nothing`);
  }
});

