const root = join(import.meta.dirname, "..");

async function project(files: Record<string, string> = {}): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "stalemap-setup-"));
  for (const [name, text] of Object.entries(files)) {
    await mkdir(join(dir, name, ".."), { recursive: true });
    await writeFile(join(dir, name), text);
  }
  return dir;
}

const BLOCK = "<!-- stalemap:start -->\n<!-- generated by stalemap 2026-10-16 · model=m · cutoff=2025-07-31 · deps=0123456789ab -->\n**ai** 4 → 7\n<!-- stalemap:end -->";
const notes: NotesRenderer = async () => ({ block: BLOCK });
/** Same notes, generated on another day: setup must not rewrite the file for the date. */
const notesLater: NotesRenderer = async () => ({ block: BLOCK.replace("2026-10-16", "2026-11-02") });
const run = (agent: SetupAgent, cwd: string, extra: Partial<Parameters<typeof setupAgent>[0]> = {}) =>
  setupAgent({ agent, cwd, renderNotes: notes, home: cwd, ...extra });
const read = (dir: string, f: string) => readFile(join(dir, f), "utf8");
const readJson = async (dir: string, f: string) => JSON.parse(await read(dir, f));

const EXPECTED_FILES: Record<SetupAgent, string[]> = {
  cursor: ["AGENTS.md", ".cursor/mcp.json", ".cursor/hooks.json"],
  codex: ["AGENTS.md", ".codex/config.toml", ".codex/hooks.json"],
  opencode: ["AGENTS.md", "opencode.json", ".opencode/plugins/stalemap.js"],
  claude: ["CLAUDE.md", ".mcp.json", ".claude/settings.json"],
};

for (const agent of SETUP_AGENTS) {
  test(`setup --agent ${agent} writes the notes, the MCP server and the guard, and a re-run changes nothing`, async () => {
    const dir = await project({ "package.json": "{}" });
    const first = await run(agent, dir);
    assert.deepEqual(
      first.changes.map((c) => `${c.action} ${c.file}`),
      EXPECTED_FILES[agent].map((f) => `create ${f}`),
    );
    for (const f of EXPECTED_FILES[agent]) assert.ok(existsSync(join(dir, f)), f);
    assert.ok((await read(dir, EXPECTED_FILES[agent][0]!)).includes("**ai** 4 → 7"));

    const again = await run(agent, dir, { renderNotes: notesLater });
    assert.deepEqual(new Set(again.changes.map((c) => c.action)), new Set(["unchanged"]));
    assert.equal(again.files.size, 0);
  });
}

