import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, writeFileSync } from "node:fs";
import { createRequire, register } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = fileURLToPath(new URL("../../", import.meta.url));
const load = (id: string): Promise<any> => import(id);
const requireFromApp = createRequire(join(root, "package.json"));
test("getDictionary() follows the [lang] of the route being rendered", async () => {
  await load("next/dist/server/node-environment-baseline.js");
  // `next/root-params` is generated by Next's compiler from the app's root layouts; generate it with Next's own loader.
  const loaderModule = await load("next/dist/build/webpack/loaders/next-root-params-loader.js");
  const rootParamsLoader = typeof loaderModule.default === "function" ? loaderModule.default : loaderModule.default.default;
  const source: string = await rootParamsLoader.call({ getOptions: () => ({ appDir: join(root, "app"), pageExtensions: ["tsx", "ts", "jsx", "js"] }), addContextDependency() {} });
  const runtime = pathToFileURL(requireFromApp.resolve("next/dist/server/request/root-params.js")).href;
  const file = join(mkdtempSync(join(tmpdir(), "next-root-params-")), "root-params.mjs");
  writeFileSync(file, source.replaceAll("'next/dist/server/request/root-params'", JSON.stringify(runtime)));
  const hook = `export async function resolve(s, c, n) { return s === "next/root-params" ? { url: ${JSON.stringify(pathToFileURL(file).href)}, shortCircuit: true } : n(s, c); }`;
  register("data:text/javascript," + encodeURIComponent(hook));
  // Render-time context, as Next sets it up for a request to /<lang>.
  const { workAsyncStorage } = await load("next/dist/server/app-render/work-async-storage.external.js");
  const { workUnitAsyncStorage } = await load("next/dist/server/app-render/work-unit-async-storage.external.js");
  const { getDictionary } = await load("../../src/i18n.ts");
  const { dictionaries } = await load("../../src/dictionaries.ts");
  const during = (lang: string) =>
    workAsyncStorage.run({ route: "/[lang]", page: "/[lang]/page" }, () =>
      workUnitAsyncStorage.run({ type: "request", phase: "render", rootParams: { lang } }, () => getDictionary()),
    );
  assert.deepEqual(await during("fr"), dictionaries.fr);
  assert.deepEqual(await during("de"), dictionaries.de);
  assert.deepEqual(await during("en"), dictionaries.en);
  assert.deepEqual(await during("pt"), dictionaries.en, "unknown locales fall back to English");
});
