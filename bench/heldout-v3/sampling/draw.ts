/**
 * The heldout-v3 draw (see ../PROTOCOL.md, "Sampling"). Every change in population.jsonl gets a rank:
 * sha256("heldout-v3:<SEED>:<change id>"), lowest first. Because each rank depends only on the seed and the change's
 * own id, adding or removing an entry never reorders the others. Tasks are built by walking this order and skipping
 * changes that meet a pre-registered skip criterion; the outcome of every change walked is recorded in walk/<package>.jsonl.
 *
 *   npx tsx bench/heldout-v3/sampling/draw.ts            # writes draw.md (the full order, with outcomes so far)
 *   npx tsx bench/heldout-v3/sampling/draw.ts --check    # also fails if population ids aren't unique, or the walk
 *                                                        # passes over a change or names one that isn't in the population
 */
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const HERE = dirname(fileURLToPath(import.meta.url));
/** Fixed before the population was built: claude-sonnet-4-5's training cutoff, as a number. */
export const SEED = 20250731;

export interface Change {
  id: string;
  package: string;
  version: string;
  date: string;
  type: "breaking" | "deprecation" | "default-behavior";
  summary: string;
  source: string;
}
export interface Walked {
  id: string;
  outcome: "task" | "skip";
  /** The task folder, when outcome is "task". */
  task?: string;
  /** Skip criterion (S1–S8 in PROTOCOL.md) and a sentence, when outcome is "skip". */
  criterion?: string;
  reason?: string;
}

export const rank = (id: string) => createHash("sha256").update(`heldout-v3:${SEED}:${id}`).digest("hex");

const jsonl = async <T>(file: string): Promise<T[]> =>
  existsSync(file) ? (await readFile(file, "utf8")).split("\n").filter((l) => l.trim()).map((l) => JSON.parse(l) as T) : [];

async function main(): Promise<void> {
  const { values } = parseArgs({ options: { check: { type: "boolean" } } });
  const population = await jsonl<Change>(join(HERE, "population.jsonl"));
  const walkDir = join(HERE, "walk");
  const walkFiles = existsSync(walkDir) ? (await readdir(walkDir)).filter((f) => f.endsWith(".jsonl")).sort() : [];
  const walked = (await Promise.all(walkFiles.map((f) => jsonl<Walked>(join(walkDir, f))))).flat();
  const problems: string[] = [];
  const ids = new Set<string>();
  for (const c of population) {
    if (ids.has(c.id)) problems.push(`duplicate id ${c.id}`);
    ids.add(c.id);
  }
  const order = [...population].sort((a, b) => (rank(a.id) < rank(b.id) ? -1 : 1));
  const outcome = new Map(walked.map((w) => [w.id, w]));
  for (const w of walked) if (!ids.has(w.id)) problems.push(`the walk names ${w.id}, which isn't in the population`);
  for (const id of new Set(walked.map((w) => w.id))) if (walked.filter((w) => w.id === id).length > 1) problems.push(`the walk records ${id} more than once`);
  // The walk must be a prefix of the order: no change may be passed over without a recorded outcome.
  const lastWalked = Math.max(-1, ...order.map((c, i) => (outcome.has(c.id) ? i : -1)));
  for (let i = 0; i <= lastWalked; i++) if (!outcome.has(order[i].id)) problems.push(`change #${i + 1} (${order[i].id}) was passed over without an outcome`);

  const byPackage = new Map<string, number>();
  for (const c of population) byPackage.set(c.package, (byPackage.get(c.package) ?? 0) + 1);
  const lines = [
    "# heldout-v3 draw",
    "",
    `Generated by \`draw.ts\` from \`population.jsonl\` (${population.length} changes) with seed ${SEED}. Order: sha256("heldout-v3:${SEED}:<id>"), lowest first. Outcomes come from \`walk/*.jsonl\`.`,
    "",
    "| package | changes in population |",
    "|---|---|",
    ...[...byPackage].sort((a, b) => b[1] - a[1]).map(([p, n]) => `| ${p} | ${n} |`),
    "",
    `Walked so far: ${walked.length} (${walked.filter((w) => w.outcome === "task").length} tasks, ${walked.filter((w) => w.outcome === "skip").length} skipped).`,
    "",
    "| # | change | type | summary | outcome |",
    "|---|---|---|---|---|",
    ...order.map((c, i) => {
      const w = outcome.get(c.id);
      const o = !w ? "" : w.outcome === "task" ? `task \`${w.task}\`` : `skip ${w.criterion}: ${w.reason}`;
      return `| ${i + 1} | \`${c.id}\` | ${c.type} | ${c.summary.replace(/\|/g, "\\|")} | ${o.replace(/\|/g, "\\|")} |`;
    }),
  ];
  await writeFile(join(HERE, "draw.md"), lines.join("\n") + "\n");
  if (values.check && problems.length) {
    process.stderr.write(problems.map((p) => `- ${p}`).join("\n") + "\n");
    process.exit(1);
  }
  process.stdout.write(`draw.md: ${order.length} changes, ${walked.length} walked${problems.length ? `, ${problems.length} problem(s)` : ""}\n`);
}

main().catch((err) => {
  process.stderr.write(`draw: ${(err as Error).stack ?? err}\n`);
  process.exit(1);
});
