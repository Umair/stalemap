// Builds the pull-request comment from `stalemap scan --json` output. Prints nothing when no
// dependency changed after the cutoff, so run.sh can skip or clear the comment.
import { readFileSync } from "node:fs";

const [file, marker] = process.argv.slice(2);
const scan = JSON.parse(readFileSync(file, "utf8"));
const changed = scan.reports.filter((r) => r.status === "changed" || r.status === "new");
if (!changed.length) process.exit(0);

const inner = scan.block
  .split("\n")
  .filter((line) => !line.startsWith("<!-- stalemap:") && !line.startsWith("<!-- generated by stalemap"))
  .join("\n")
  .replace(/^## .*\n/m, "")
  .trim();

const rows = changed
  .map((r) => (r.status === "new" ? `| \`${r.name}\` | — | ${r.pinned} | new since cutoff |` : `| \`${r.name}\` | ${r.baseline.version} | ${r.pinned} | ${r.major ? "major" : ""} |`))
  .join("\n");

process.stdout.write(`${marker}
### stalemap: ${changed.length} dependenc${changed.length === 1 ? "y" : "ies"} changed after \`${scan.model.id}\`'s training cutoff (${scan.model.cutoff})

| package | model knows | pinned | |
|---|---|---|---|
${rows}

<details><summary>Notes for the agent</summary>

${inner}

</details>

<sub>Run \`npx stalemap sync\` to put these notes in ${scan.target}.</sub>
`);
